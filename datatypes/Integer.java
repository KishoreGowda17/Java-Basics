package datatypes;

public class Integer 
{
    public static void main(String[] args) 
    {
        byte b1 = 10; //decimal
        byte b2 = 0b1010; // binary
        byte b3 = 012; // Octal
        byte b4 = 0xA; // Hexadecimal

        System.out.println(b1);
        System.out.println(b2);
        System.out.println(b3);
        System.out.println(b4);
    }

}
